    private fun km(m: Int) = if (m % 1000 == 0) "${m / 1000}" else String.format(java.util.Locale.ROOT, "%.1f", m / 1000.0).replace('.', ',')

    private fun plural(n: Int, one: String, few: String, many: String): String {
        val m10 = n % 10
        val m100 = n % 100
        return when {
            m10 == 1 && m100 != 11 -> one
            m10 in 2..4 && m100 !in 12..14 -> few
            else -> many
        }
    }

